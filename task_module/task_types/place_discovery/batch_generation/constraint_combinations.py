"""Deterministic private comparison/combination layer for Discovery.

Atoms are supplied by factual extractors, not generated by the writer. Missing
facts required by a selected condition count as not satisfying that condition.
This module does not change legacy generators or score historical tasks.
"""
from __future__ import annotations

from itertools import combinations
import json
import random
from typing import Any

from app.runtime.geo import distance_m


def rank_five_pool(target: dict, candidates: list[dict]) -> dict:
    """Candidates must already satisfy the explicit base type/service C."""
    origin = target.get("location") or target.get("coordinate") or target
    ranked = []
    seen = {target["place_id"]}
    for place in sorted(candidates, key=lambda p: p["place_id"]):
        if place["place_id"] in seen:
            continue
        seen.add(place["place_id"])
        point = place.get("location") or place.get("coordinate") or place
        for coords in (origin, point):
            if not isinstance(coords.get("lat"), (int, float)) or not isinstance(coords.get("lng"), (int, float)):
                raise ValueError("Missing frozen coordinates; cannot establish comparison pool")
        ranked.append((distance_m(origin, point), place))
    ranked.sort(key=lambda item: (item[0], item[1]["place_id"]))
    if not ranked:
        raise ValueError("No non-GT comparison POI")
    radius = ranked[min(4, len(ranked) - 1)][0]
    return {"radius_m": radius, "sampling_only": True,
            "places": [target, *(p for d, p in ranked if d <= radius)]}


def build_options(*, target_id: str, candidate_ids: list[str],
                  base_constraints: list[dict], atoms: list[dict],
                  rng: random.Random) -> dict[str, Any]:
    """Find minimum cores, add 0–2 sourced auxiliary atoms, sample 6–8 options.

Each atom has constraint_id, constraint, source and matches {POI: bool|None}.
Only explicit True satisfies a selected condition. Different factual dimensions are
not collapsed merely because their matching POI sets happen to be equal.
"""
    universe = set(candidate_ids)
    if target_id not in universe or len(universe) < 2:
        raise ValueError("Comparison pool must contain GT and competitors")
    usable = []
    signatures = set()
    ids = set()
    for atom in sorted(atoms, key=lambda a: a["constraint_id"]):
        if atom["constraint_id"] in ids:
            raise ValueError("Duplicate constraint_id")
        ids.add(atom["constraint_id"])
        if not atom.get("source"):
            raise ValueError("Atom requires frozen source evidence")
        matches = atom.get("matches", {})
        if any(value is not None and type(value) is not bool for value in matches.values()):
            raise ValueError("matches values must be bool or None")
        if matches.get(target_id) is not True:
            continue
        signature = json.dumps(atom["constraint"], sort_keys=True, ensure_ascii=False)
        if signature not in signatures:
            signatures.add(signature)
            usable.append({**atom, "matches": {pid: matches.get(pid) is True for pid in universe}})

    def remaining(selected):
        return {pid for pid in universe
                if all(a["matches"].get(pid) is True for a in selected)}

    def compatible(selected):
        modes = {a["constraint"].get("mode") for a in selected
                 if a["constraint"].get("mode")}
        # One journey cannot simultaneously require different modes. Do not
        # repeat multiple versions of the same factual requirement either.
        dimensions = [(a["constraint"].get("type"), a["constraint"].get("value")
                       if a["constraint"].get("type") == "service_feature" else None)
                      for a in selected]
        return len(modes) <= 1 and len(dimensions) == len(set(dimensions))

    cores = []
    for size in range(1, len(usable) + 1):
        cores = [group for group in combinations(usable, size)
                 if compatible(group) and remaining(group) == {target_id}]
        if cores:
            break
    if not cores:
        raise ValueError("No unique core proven by supplied public facts")
    full_options = {}
    for core in cores:
        core_ids = {a["constraint_id"] for a in core}
        extras = [a for a in usable if a["constraint_id"] not in core_ids]
        for count in range(min(2, len(extras)) + 1):
            for auxiliary in combinations(extras, count):
                selected = (*core, *auxiliary)
                if not compatible(selected):
                    continue
                key = tuple(sorted(a["constraint_id"] for a in selected))
                if key in full_options:
                    continue
                full_options[key] = {
                    "base_constraints": base_constraints,
                    "core_ids": sorted(core_ids),
                    "auxiliary_ids": [a["constraint_id"] for a in auxiliary],
                    "constraints": [a["constraint"] for a in selected],
                    "matching_place_ids": sorted(remaining(selected)),
                    "checks": {pid: {a["constraint_id"]: a["matches"].get(pid)
                                    for a in selected} for pid in sorted(universe)},
                }
    ordered = [full_options[key] for key in sorted(full_options)]
    requested = rng.randint(6, 8)
    chosen = rng.sample(ordered, min(requested, len(ordered)))
    for i, option in enumerate(chosen, 1):
        option["option_id"] = f"option_{i:03d}"
    return {"minimum_core_size": len(cores[0]), "minimum_core_count": len(cores),
            "valid_option_count": len(ordered), "requested_option_count": requested,
            "options": chosen, "atom_evidence": usable,
            "comparison_place_ids": sorted(universe)}

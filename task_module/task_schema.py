"""Benchmark task data models for pipeline_v2 task_module.

Event nodes (Phase 1):
  - EnvEventNode: virtual environment events (weather, transit, service, actor, system)
  - JudgeNode: agent action verification checkpoints (service_operation, communication, navigation)

Assembled tasks (Phase 2):
  - BenchmarkTask: complete benchmark scenario with world_slice, env_events, judge_sequence
  - TaskSet: container for all tasks
  - BenchmarkManifest: task index for vis
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any


# ============================================================
# Phase 1: Event Node Primitives
# ============================================================

@dataclass
class StateEffect:
    """A single state change applied by an environment event."""
    target_type: str = ""              # "service" | "place" | "corridor" | "actor" | "district"
    target_id_pattern: str = ""        # "SERVICE_ID" | "ALL_IN_DISTRICT" | specific id
    field_path: str = ""               # e.g., "state_model.crowding_level"
    op: str = "set"                    # "set" | "multiply" | "add" | "remove"
    value: Any = None
    duration_seconds: int | None = None  # None = lasts for the task duration


@dataclass
class EnvEventNode:
    """Virtual environment event — simulates real-world perturbations.

    Generated by LLM from world.json + characters.json context.
    Injected into the runtime during benchmark execution to test
    the agent's adaptability.
    """
    node_id: str = ""                  # "env_tokyo_rain_shibuya_001"
    category: str = ""                 # "weather" | "transit" | "service" | "actor_condition" | "actor_preference_change" | "system"
    scope_type: str = ""               # "district" | "corridor" | "place" | "service" | "actor"
    scope_id: str | None = None        # specific target object id, or None for pattern-matched
    effects: list[StateEffect] = field(default_factory=list)
    trigger_mode: str = "random"       # "random" | "time_based" | "conditional" | "always"
    trigger_probability: float = 1.0   # 0.0 ~ 1.0
    trigger_delay_seconds: int | None = None
    visibility: str = "visible"        # "visible" | "hidden" | "delayed"
    description_zh: str = ""           # human-readable Chinese description
    severity: str = "medium"           # "low" | "medium" | "high"
    source: str = ""                   # "llm_generated" | "derived_from_character"


@dataclass
class CheckItem:
    """A single verification criterion for a judge node."""
    check_type: str = ""               # "action_executed" | "field_equals" | "field_contains" | "field_in_set" | "field_not_empty" | "order_correct"
    field: str = ""                    # field path to check, e.g., "args.party_size"
    expected: Any = None               # expected value
    tolerance: dict[str, Any] | None = None  # {"minutes": 15, "meters": 500}
    weight: str = "hard"               # "hard" | "soft"


@dataclass
class AgentAction:
    """The action an agent should perform at a judgment checkpoint."""
    app: str = ""                      # "LocalServiceApp" | "MessagingAppV2" | "MobilityApp" | "UserInterfaceApp"
    function: str = ""                 # "search_services" | "make_reservation" | "send_message" | "check_route"
    arg_slots: dict[str, Any] = field(default_factory=dict)  # slot placeholder, filled at assembly time


@dataclass
class JudgeNode:
    """Judgment node — verifies agent output at each checkpoint.

    Derived from service affordances, character relationships,
    and spatial connections. NOT LLM-generated.
    """
    node_id: str = ""                  # "jcp_search_restaurant_001"
    category: str = ""                 # "service_operation" | "communication" | "navigation" | "information_lookup"
    agent_action: AgentAction = field(default_factory=AgentAction)
    checks: list[CheckItem] = field(default_factory=list)
    depends_on: list[str] = field(default_factory=list)  # prerequisite node_ids
    description_zh: str = ""           # human-readable Chinese description
    source: str = "rule_derived"       # "rule_derived"


# ============================================================
# Phase 1 Output Container
# ============================================================

@dataclass
class EventNodeSet:
    """All generated event nodes (Phase 1 output)."""
    schema_version: str = "v2.events.v1"
    city_id: str = ""
    generated_at: str = ""
    env_events: list[EnvEventNode] = field(default_factory=list)
    judge_nodes: list[JudgeNode] = field(default_factory=list)
    generation_stats: dict[str, Any] = field(default_factory=dict)


# ============================================================
# Phase 2: Task Assembly
# ============================================================

@dataclass
class WorldSliceSummary:
    """Summary of world objects involved in a task — for vis display."""
    characters: list[dict[str, Any]] = field(default_factory=list)
    places: list[dict[str, Any]] = field(default_factory=list)
    services: list[dict[str, Any]] = field(default_factory=list)
    districts: list[dict[str, Any]] = field(default_factory=list)
    corridors: list[dict[str, Any]] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        from dataclasses import asdict
        return asdict(self)


@dataclass
class JudgeStage:
    """A group of judge nodes forming one phase of the oracle sequence."""
    stage_id: str = ""                 # "stage_1_search"
    description: str = ""              # "阶段1：搜索和查询"
    depends_on: list[str] = field(default_factory=list)  # prerequisite stage_ids
    nodes: list[JudgeNode] = field(default_factory=list)  # judge nodes in this stage


@dataclass
class TaskTypeConfig:
    """Metadata config for a task type — used by registry."""
    task_type: str = ""
    category: str = ""                 # "atomic" | "compositional" | "overlay"
    label_zh: str = ""                 # Chinese label
    description: str = ""              # Brief description
    default_count: int = 100           # Default number of tasks to generate
    default_difficulty: str = "mixed"
    min_chars: int = 0
    max_chars: int = 10
    preferred_service_types: list[str] = field(default_factory=list)
    env_event_categories: list[str] = field(default_factory=list)



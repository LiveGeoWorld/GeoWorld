@dataclass
class ManifestEntry:
    """A single task entry in the benchmark manifest."""
    task_id: str = ""
    folder: str = ""                   # "task_001_今晚请帮我协"
    task_type: str = ""                # "place_grounding"
    query_preview: str = ""            # first 20 chars of user_prompt
    scenario_type: str = ""            # DEPRECATED
    difficulty: str = ""
    characters: list[str] = field(default_factory=list)
    env_event_count: int = 0
    judge_stages: int = 0
    review_status: str = ""
    prompt_language: str = ""
    grounding_target_type: str = ""
    acceptable_granularity: str = ""
    category: str = ""
    service_type: str = ""
    top_candidate: str = ""
    quality_passed: bool | None = None


@dataclass
class BenchmarkManifest:
    """Task index for vis browsing (benchmark_manifest.json)."""
    city_id: str = ""
    variant: str = ""
    generated_at: str = ""
    task_count: int = 0
    tasks: list[ManifestEntry] = field(default_factory=list)
    tasks_by_type: dict[str, list[ManifestEntry]] = field(default_factory=dict)
    schema_version: str = "v2.manifest.v1"

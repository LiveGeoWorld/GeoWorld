@dataclass
class BenchmarkTask:
    """A complete benchmark task assembled from event nodes."""
    task_id: str = ""
    task_type: str = ""                # one of TASK_TYPES keys, e.g. "place_grounding"
    scenario_type: str = ""            # DEPRECATED: use task_type instead
    difficulty: str = "medium"         # "easy" | "medium" | "hard"
    city_id: str = ""
    variant: str = ""
    generated_at: str = ""
    user_prompt: str = ""              # The ONLY input given to the agent
    summary: dict[str, Any] = field(default_factory=dict)
    time_context: dict[str, Any] = field(default_factory=dict)

    # World slice
    world_slice: dict[str, list[str]] = field(default_factory=dict)
    #   { "district_ids": [...], "corridor_ids": [...], "place_ids": [...],
    #     "service_ids": [...], "character_ids": [...],
    #     "info_ids": [...], "event_template_ids": [...] }

    # World slice summary for vis display (human-readable names + details)
    world_slice_summary: WorldSliceSummary = field(default_factory=WorldSliceSummary)

    # Environment events that may trigger during this task
    involved_env_events: list[str] = field(default_factory=list)
    env_event_details: list[EnvEventNode] = field(default_factory=list)

    # Judge sequence grouped into stages
    judge_stages: list[JudgeStage] = field(default_factory=list)

    # Generation metadata
    metadata: dict[str, Any] = field(default_factory=dict)



"""Orchestrate map-world overlay generation.

The substrate comes from real geography. The overlay remains scoped to map,
service, public information, and dynamic city/service events. Non-map entities
are generated by downstream modules, not world_module.map.
"""

from __future__ import annotations

import random
from datetime import datetime, timezone
from typing import Any

from shared.io import to_plain
from world_module.map._internal.builders.information_ecology_builder import build_information_ecology
from world_module.map._internal.builders.semantic_shard_builder import apply_semantic_shards, build_semantic_shards


def add_live_overlay(
    world: dict[str, Any],
    seed: Any,
    discovery: dict[str, Any] | None = None,
    *,
    model: str = "gpt-5.5",
    endpoint_name: str = "cliproxy_gpt55_pro",
    config_path: str | None = None,
) -> dict[str, Any]:
    discovery = discovery or {}
    rng = random.Random(seed.city_id)
    built_at = datetime.now(timezone.utc).isoformat()
    services: list[dict[str, Any]] = []
    places_by_id = {p["place_id"]: p for p in world.get("places", [])}

    semantic_shards = build_semantic_shards(
        world, seed, discovery, model=model, endpoint_name=endpoint_name, config_path=config_path,
    )
    apply_semantic_shards(world, semantic_shards)

    information_ecology = build_information_ecology(
        world,
        services,
        places_by_id,
        rng,
        built_at,
        discovery.get("dynamic_storylines", []),
    )
    information = information_ecology["information_items"]

    world.pop("actors", None)
    world.pop("peripheral_contacts", None)
    world.pop("public_personas", None)
    world.pop("social_graph", None)
    world.pop("social_app_projections", None)
    world["information_items"] = to_plain(information)
    world["information_graph"] = information_ecology["information_graph"]
    world["event_templates"] = []
    world.pop("information", None)

    world["generation_metadata"]["live_overlay"] = {
        "information_count": len(information),
        "event_template_count": 0,
        "overlay_policy": "factual_place_details_and_google_reviews_only",
        "dynamic_service_state_policy": "not_written_to_base_city_world",
        "non_map_entity_policy": "generated_by_downstream_modules",
        "llm_storyline_count": len(discovery.get("dynamic_storylines", [])),
        "semantic_shard_quality": semantic_shards.get("quality", {}),
        "semantic_shard_policy": semantic_shards.get("policy", {}),
        "information_quality": information_ecology["information_quality"],
    }
    return world

"""LLM semantic shard builder for v7 live city worlds.

Real facts are already in the substrate by the time this builder runs. This
stage asks the model for small, local patches that make the world easier for a
ScenarioDesignerAgent to operate: task roles, risks, substitutes, and information
seeds. Character profiles are generated by world_module.character, not world_module.map.
"""

from __future__ import annotations

import json
from concurrent.futures import ThreadPoolExecutor, as_completed
from typing import Any

from shared.llm_client import YunwuResponsesClient
from world_module.map._internal.yunwu_city_search import extract_json_object, extract_response_text


def build_semantic_shards(
    world: dict[str, Any],
    seed: Any,
    discovery: dict[str, Any],
    *,
    model: str = "gpt-5.5",
    endpoint_name: str = "cliproxy_gpt55_pro",
    config_path: str | None = None,
) -> dict[str, Any]:
    if not getattr(seed, "llm_semantic_shards", True):
        return _empty_result("disabled_by_seed")

    max_workers = max(1, int(getattr(seed, "llm_semantic_max_workers", 6)))
    client = YunwuResponsesClient(
        model=model,
        endpoint_name=endpoint_name,
        config_path=config_path,
        timeout_seconds=int(getattr(seed, "llm_semantic_timeout_seconds", 120)),
    )
    places_by_district = _group_places_by_district(world.get("places", []))
    places_by_corridor = _group_places_by_corridor(world.get("places", []))
    services_by_place = {s.get("place_id"): s for s in world.get("services", [])}

    errors: list[str] = []
    district_jobs = [
        _district_payload(district, places_by_district.get(district["district_id"], []), services_by_place, seed)
        for district in world.get("districts", [])
    ]
    corridor_jobs = [
        _corridor_payload(corridor, places_by_corridor.get(corridor["corridor_id"], []), services_by_place, seed)
        for corridor in world.get("corridors", [])
    ]

    print(
        "[semantic] shards "
        f"districts={len(district_jobs)}, corridors={len(corridor_jobs)}, "
        f"workers={max_workers}",
        flush=True,
    )

    district_docs = _parallel_json_calls(
        client,
        [_district_prompt(seed, payload) for payload in district_jobs],
        max_workers=max_workers,
        max_output_tokens=4500,
        errors=errors,
        label="district",
    )
    corridor_docs = _parallel_json_calls(
        client,
        [_corridor_prompt(seed, payload) for payload in corridor_jobs],
        max_workers=max_workers,
        max_output_tokens=4500,
        errors=errors,
        label="corridor",
    )
    result = {
        "district_patches": {},
        "corridor_patches": {},
        "place_patches": {},
        "service_patches": {},
        "errors": errors,
        "policy": {
            "mode": "parallel_semantic_shards",
            "model": model,
            "endpoint_name": endpoint_name,
            "max_workers": max_workers,
            "timeout_seconds": getattr(seed, "llm_semantic_timeout_seconds", 120),
            "district_place_limit": getattr(seed, "llm_district_place_limit", 18),
            "corridor_place_limit": getattr(seed, "llm_corridor_place_limit", 18),
        },
    }

    for doc in district_docs:
        _merge_patch_doc(result, doc)
    for doc in corridor_docs:
        _merge_patch_doc(result, doc)
    result["quality"] = {
        "ok": not errors,
        "district_patch_count": len(result["district_patches"]),
        "corridor_patch_count": len(result["corridor_patches"]),
        "place_patch_count": len(result["place_patches"]),
        "service_patch_count": len(result["service_patches"]),
        "error_count": len(errors),
    }
    return result


def apply_semantic_shards(world: dict[str, Any], semantic: dict[str, Any]) -> None:
    district_patches = semantic.get("district_patches", {})
    corridor_patches = semantic.get("corridor_patches", {})
    place_patches = semantic.get("place_patches", {})
    service_patches = semantic.get("service_patches", {})

    for district in world.get("districts", []):
        patch = district_patches.get(district.get("district_id"))
        if not patch:
            continue
        _extend_unique(district.setdefault("role_tags", []), patch.get("semantic_tags", []))
        notes = district.setdefault("director_notes", {})
        notes["llm_semantic"] = _compact_patch(patch)
        risk_profile = district.setdefault("risk_profile", {})
        if patch.get("dynamic_risks"):
            risk_profile["llm_dynamic_risks"] = patch["dynamic_risks"]

    for corridor in world.get("corridors", []):
        patch = corridor_patches.get(corridor.get("corridor_id"))
        if not patch:
            continue
        tags = corridor.setdefault("control_tags", {}).setdefault("sampler_axes", [])
        _extend_unique(tags, patch.get("semantic_tags", []))
        corridor.setdefault("director_notes", {})["llm_semantic"] = _compact_patch(patch)
        mobility = corridor.setdefault("base_mobility_model", {})
        if patch.get("dynamic_risks"):
            mobility["llm_dynamic_risks"] = patch["dynamic_risks"]

    for place in world.get("places", []):
        patch = place_patches.get(place.get("place_id"))
        if not patch:
            continue
        place.setdefault("director_notes", {})["llm_semantic"] = _compact_patch(patch)
        tags = place.setdefault("control_tags", {}).setdefault("semantic_tags", [])
        _extend_unique(tags, patch.get("semantic_tags", []))

    for service in world.get("services", []):
        patch = service_patches.get(service.get("service_id"))
        if not patch:
            continue
        service.setdefault("director_notes", {})["llm_semantic"] = _compact_patch(patch)
        state = service.setdefault("state_model", {})
        if patch.get("operational_risks"):
            state["llm_operational_risks"] = patch["operational_risks"]
        if patch.get("information_seed"):
            state["llm_information_seed"] = patch["information_seed"]


def _parallel_json_calls(
    client: YunwuResponsesClient,
    prompts: list[str],
    *,
    max_workers: int,
    max_output_tokens: int,
    errors: list[str],
    label: str,
) -> list[dict[str, Any]]:
    if not prompts:
        return []
    results: list[dict[str, Any]] = []
    workers = max(1, min(max_workers, len(prompts)))
    with ThreadPoolExecutor(max_workers=workers) as executor:
        future_to_index = {
            executor.submit(_call_one_json, client, prompt, max_output_tokens): index
            for index, prompt in enumerate(prompts)
        }
        for future in as_completed(future_to_index):
            index = future_to_index[future]
            try:
                results.append(future.result())
            except Exception as exc:
                errors.append(f"{label}_shard_{index}: {exc}")
    print(f"[semantic] {label}_done={len(results)}/{len(prompts)}", flush=True)
    return results


def _call_one_json(client: YunwuResponsesClient, prompt: str, max_output_tokens: int) -> dict[str, Any]:
    response = client.call(prompt, extra={"max_output_tokens": max_output_tokens})
    return extract_json_object(extract_response_text(response))


def _merge_patch_doc(result: dict[str, Any], doc: dict[str, Any]) -> None:
    district = doc.get("district_patch")
    if isinstance(district, dict) and district.get("district_id"):
        result["district_patches"][district["district_id"]] = district
    corridor = doc.get("corridor_patch")
    if isinstance(corridor, dict) and corridor.get("corridor_id"):
        result["corridor_patches"][corridor["corridor_id"]] = corridor
    for patch in doc.get("place_patches", []) or []:
        if isinstance(patch, dict) and patch.get("place_id"):
            result["place_patches"][patch["place_id"]] = patch
    for patch in doc.get("service_patches", []) or []:
        if isinstance(patch, dict) and patch.get("service_id"):
            result["service_patches"][patch["service_id"]] = patch


def _district_prompt(seed: Any, payload: dict[str, Any]) -> str:
    return _prompt(
        seed,
        "Design one district shard. Patch only the provided IDs. Do not invent places.",
        {
            "input": payload,
            "output_schema": {
                "district_patch": {
                    "district_id": payload["district"]["district_id"],
                    "semantic_tags": ["short tags"],
                    "task_roles": ["goals this district supports"],
                    "dynamic_risks": ["risks useful for events"],
                    "local_knowledge": ["tips agents may need"],
                },
                "place_patches": [
                    {
                        "place_id": "from input",
                        "semantic_tags": ["quiet|crowded|fallback|landmark|..."],
                        "task_roles": ["why useful for benchmark tasks"],
                        "substitution_logic": "when this can replace another option",
                        "information_seed": "review/post/tip seed",
                    }
                ],
                "service_patches": [
                    {
                        "service_id": "from input",
                        "operational_risks": ["slot_loss|queue|closure|language|weather"],
                        "information_seed": "what public info may conflict",
                        "task_value": "why this service is executable/useful",
                    }
                ],
            },
        },
    )


def _corridor_prompt(seed: Any, payload: dict[str, Any]) -> str:
    return _prompt(
        seed,
        "Design one corridor shard. Patch only the provided IDs. Focus on mobility-service interaction.",
        {
            "input": payload,
            "output_schema": {
                "corridor_patch": {
                    "corridor_id": payload["corridor"]["corridor_id"],
                    "semantic_tags": ["short tags"],
                    "task_roles": ["what tasks this corridor enables"],
                    "dynamic_risks": ["delay|crowding|transfer|weather|last_train"],
                    "service_band_logic": "how places cluster along this corridor",
                },
                "place_patches": [
                    {
                        "place_id": "from input",
                        "semantic_tags": ["node_anchor|fallback|crowded|..."],
                        "task_roles": ["why useful near corridor"],
                        "substitution_logic": "when useful as fallback",
                        "information_seed": "post/tip seed",
                    }
                ],
                "service_patches": [
                    {
                        "service_id": "from input",
                        "operational_risks": ["queue|slot_loss|route_delay"],
                        "information_seed": "what can become stale/conflicting",
                        "task_value": "why service matters on corridor",
                    }
                ],
            },
        },
    )


def _prompt(seed: Any, task: str, body: dict[str, Any]) -> str:
    return f"""
You are a world-building worker inside GeoAgentBench v7. The world already uses
real Google Maps objects. Your job is not to invent facts, but to add benchmark
semantics that help a ScenarioDesignerAgent create executable dynamic tasks.

Task: {task}

Principles:
- Every field must help search, scenario design, app observability, execution,
  or evaluation.
- Prefer local, concrete, operational details over generic prose.
- Keep JSON compact and valid. Return JSON only.

City: {seed.city_name}, {seed.country}. Seed id: {seed.city_id}.
{json.dumps(body, ensure_ascii=False, separators=(",", ":"))}
""".strip()


def _district_payload(
    district: dict[str, Any],
    places: list[dict[str, Any]],
    services_by_place: dict[str, dict[str, Any]],
    seed: Any,
) -> dict[str, Any]:
    limit = int(getattr(seed, "llm_district_place_limit", 18))
    selected = _select_places(places, limit)
    return {
        "district": _district_summary(district),
        "places": [_place_summary(p, services_by_place.get(p.get("place_id"))) for p in selected],
    }


def _corridor_payload(
    corridor: dict[str, Any],
    places: list[dict[str, Any]],
    services_by_place: dict[str, dict[str, Any]],
    seed: Any,
) -> dict[str, Any]:
    limit = int(getattr(seed, "llm_corridor_place_limit", 18))
    selected = _select_places(places, limit)
    return {
        "corridor": _corridor_summary(corridor),
        "places": [_place_summary(p, services_by_place.get(p.get("place_id"))) for p in selected],
    }


def _group_places_by_district(places: list[dict[str, Any]]) -> dict[str, list[dict[str, Any]]]:
    grouped: dict[str, list[dict[str, Any]]] = {}
    for place in places:
        did = place.get("district_id")
        if did:
            grouped.setdefault(did, []).append(place)
    return grouped


def _group_places_by_corridor(places: list[dict[str, Any]]) -> dict[str, list[dict[str, Any]]]:
    grouped: dict[str, list[dict[str, Any]]] = {}
    for place in places:
        for cid in place.get("near_corridor_ids", []) or []:
            grouped.setdefault(cid, []).append(place)
    return grouped


def _select_places(places: list[dict[str, Any]], limit: int) -> list[dict[str, Any]]:
    ranked = sorted(
        places,
        key=lambda p: (
            p.get("primary_type") not in {"restaurant", "cafe", "hotel", "shopping_mall", "train_station", "hospital"},
            -(p.get("map_projection", {}).get("user_rating_count") or 0),
        ),
    )
    return ranked[:limit]


def _district_summary(district: dict[str, Any]) -> dict[str, Any]:
    return {
        "district_id": district.get("district_id"),
        "name": district.get("name"),
        "role_tags": district.get("role_tags", []),
        "dominant_flows": district.get("dominant_flows", []),
        "risk_profile": district.get("risk_profile", {}),
        "director_notes": district.get("director_notes", {}),
    }


def _corridor_summary(corridor: dict[str, Any]) -> dict[str, Any]:
    return {
        "corridor_id": corridor.get("corridor_id"),
        "name": corridor.get("name"),
        "corridor_type": corridor.get("corridor_type"),
        "node_ids": corridor.get("node_ids", []),
        "base_mobility_model": corridor.get("base_mobility_model", {}),
        "director_notes": corridor.get("director_notes", {}),
    }


def _place_summary(place: dict[str, Any], service: dict[str, Any] | None) -> dict[str, Any]:
    return {
        "place_id": place.get("place_id"),
        "name": place.get("name"),
        "primary_type": place.get("primary_type"),
        "district_id": place.get("district_id"),
        "near_corridor_ids": place.get("near_corridor_ids", []),
        "rating": place.get("map_projection", {}).get("rating"),
        "user_rating_count": place.get("map_projection", {}).get("user_rating_count"),
        "service_id": service.get("service_id") if service else None,
        "service_type": service.get("service_type") if service else None,
        "affordances": service.get("affordances", []) if service else [],
    }


def _compact_patch(patch: dict[str, Any]) -> dict[str, Any]:
    return {k: v for k, v in patch.items() if k not in {"place_id", "service_id", "district_id", "corridor_id"}}


def _extend_unique(target: list[Any], values: list[Any]) -> None:
    seen = set(target)
    for value in values or []:
        if value not in seen:
            target.append(value)
            seen.add(value)


def _empty_result(reason: str) -> dict[str, Any]:
    return {
        "district_patches": {},
        "corridor_patches": {},
        "place_patches": {},
        "service_patches": {},
        "errors": [],
        "policy": {"mode": "parallel_semantic_shards", "disabled_reason": reason},
        "quality": {
            "ok": True,
            "district_patch_count": 0,
            "corridor_patch_count": 0,
            "place_patch_count": 0,
            "service_patch_count": 0,
            "error_count": 0,
        },
    }

"""Place task runner used by the unified test_runner.

This keeps place_grounding/place_discovery on the server's test_runner entry
point while reusing the judge_sequence contract generated by task_module.curated.
"""
from __future__ import annotations
import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any
from shared.io import read_json, write_json
from test_runner.place.judge_sequence import evaluate_judge_sequence
from test_runner.place.runtime import AppRuntime
from test_runner.place.session import load_session, resolve_task_dir
from test_runner.schema import AgentRunResult, MetricResult, ToolCallRecord

def run_place_manifest(manifest_path: str | Path, world_path: str | Path, output_dir: str | Path, *, mode: str='oracle') -> dict[str, Any]:
    """Run all place tasks from a benchmark_manifest.json."""
    if mode not in {'oracle', 'judge-only'}:
        raise ValueError("test_runner place mode currently supports 'oracle' or 'judge-only'")
    manifest = read_json(manifest_path)
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    results = []
    for entry in manifest.get('tasks', []):
        task_type = entry.get('task_type', '')
        if task_type not in {'place_grounding', 'place_discovery'}:
            continue
        results.append(run_place_task_folder(manifest_path=manifest_path, task_folder=entry.get('folder', ''), world_path=world_path, output_dir=output_dir, mode=mode))
    summary = {'schema_version': 'geobench.place_run_summary.v1', 'run_id': output_dir.name, 'mode': mode, 'manifest': str(manifest_path), 'task_count': len(results), 'success_count': sum((1 for item in results if item.get('success'))), 'score_avg': _avg([item.get('score', 0.0) for item in results]), 'generated_at': datetime.now(timezone.utc).isoformat()}
    write_json(output_dir / 'run_summary.json', summary)
    _write_jsonl(output_dir / 'results.jsonl', results)
    return {'summary': summary, 'results': results}

def run_place_task_folder(*, manifest_path: str | Path, task_folder: str, world_path: str | Path, output_dir: str | Path, mode: str='oracle') -> dict[str, Any]:
    """Run a place task folder with oracle replay and judge_sequence evaluation."""
    task_dir = resolve_task_dir(manifest_path, task_folder)
    session = load_session(task_dir, task_folder, world_path)
    runtime = AppRuntime(session)
    events: list[dict[str, Any]] = []
    if mode == 'oracle':
        _record_event(events, node_id='user_prompt', stage_id='task_start', app='UserInterfaceApp', function='send_message_to_agent', args={'content': session.task.get('user_prompt', '')}, response={'status': 'delivered'})
        for stage in session.judge_sequence.get('stages', []):
            for node in stage.get('nodes', []):
                action = node.get('agent_action', '')
                if '.' not in action:
                    continue
                args = dict(node.get('arg_slots', {}) or {})
                response = runtime.dispatch(action, args, node)
                (app, function) = action.split('.', 1)
                _record_event(events, node_id=node.get('node_id', ''), stage_id=stage.get('stage_id', ''), app=app, function=function, args=args, response=response)
    elif mode == 'judge-only':
        existing = Path(output_dir) / _safe_task_dir_name(session.task_id) / 'trajectory.json'
        events = read_json(existing).get('events', [])
    else:
        raise ValueError("mode must be 'oracle' or 'judge-only'")
    judge = evaluate_judge_sequence(session.judge_sequence, events)
    task_output_dir = Path(output_dir) / _safe_task_dir_name(session.task_id)
    write_json(task_output_dir / 'trajectory.json', {'schema_version': 'geobench.trajectory.v1', 'task_id': session.task_id, 'task_folder': task_folder, 'mode': mode, 'events': events})
    write_json(task_output_dir / 'judge_report.json', judge)
    report = {'task_id': session.task_id, 'task_type': session.task_type, 'task_folder': task_folder, 'success': judge['success'], 'score': judge['score'], 'completion_policy': judge['completion_policy'], 'mode': mode, 'key_node_count': judge['key_node_count'], 'hard_passed': judge['hard_passed'], 'hard_total': judge['hard_total'], 'soft_passed': judge['soft_passed'], 'soft_total': judge['soft_total'], 'trajectory_path': str(task_output_dir / 'trajectory.json'), 'judge_report_path': str(task_output_dir / 'judge_report.json'), 'rationale': judge['rationale']}
    write_json(task_output_dir / 'run_report.json', report)
    return report

def run_place_task_dir(task_dir: str | Path, *, world_path: str | Path, output_dir: str | Path, mode: str='oracle') -> dict[str, Any]:
    """Run a concrete place task directory without requiring a manifest."""
    task_dir = Path(task_dir)
    session = load_session(task_dir, task_dir.name, world_path)
    runtime = AppRuntime(session)
    events: list[dict[str, Any]] = []
    if mode != 'oracle':
        raise ValueError('run_place_task_dir currently supports oracle mode')
    _record_event(events, node_id='user_prompt', stage_id='task_start', app='UserInterfaceApp', function='send_message_to_agent', args={'content': session.task.get('user_prompt', '')}, response={'status': 'delivered'})
    for stage in session.judge_sequence.get('stages', []):
        for node in stage.get('nodes', []):
            action = node.get('agent_action', '')
            if '.' not in action:
                continue
            args = dict(node.get('arg_slots', {}) or {})
            response = runtime.dispatch(action, args, node)
            (app, function) = action.split('.', 1)
            _record_event(events, node_id=node.get('node_id', ''), stage_id=stage.get('stage_id', ''), app=app, function=function, args=args, response=response)
    judge = evaluate_judge_sequence(session.judge_sequence, events)
    task_output_dir = Path(output_dir) / _safe_task_dir_name(session.task_id)
    write_json(task_output_dir / 'trajectory.json', {'schema_version': 'geobench.trajectory.v1', 'task_id': session.task_id, 'task_folder': task_dir.name, 'mode': mode, 'events': events})
    write_json(task_output_dir / 'judge_report.json', judge)
    report = {'task_id': session.task_id, 'task_type': session.task_type, 'task_folder': task_dir.name, 'success': judge['success'], 'score': judge['score'], 'completion_policy': judge['completion_policy'], 'mode': mode, 'key_node_count': judge['key_node_count'], 'hard_passed': judge['hard_passed'], 'hard_total': judge['hard_total'], 'soft_passed': judge['soft_passed'], 'soft_total': judge['soft_total'], 'trajectory_path': str(task_output_dir / 'trajectory.json'), 'judge_report_path': str(task_output_dir / 'judge_report.json'), 'rationale': judge['rationale']}
    write_json(task_output_dir / 'run_report.json', report)
    return report

def place_report_to_agent_result(report: dict[str, Any], task_dir: Path) -> AgentRunResult:
    """Adapt place judge reports to the existing test_runner result schema."""
    task = read_json(task_dir / 'task.json')
    passed = bool(report.get('success'))
    metric = MetricResult(metric='judge_sequence', label='标准答案 / Judge Flow', pass_=passed, detail=report.get('rationale', ''), score=1 if passed else 0)
    return AgentRunResult(task_id=report.get('task_id', task.get('task_id', '')), user_prompt=task.get('user_prompt', ''), gt_route_id='', metrics=[metric], total_metrics=1, passed_metrics=1 if passed else 0, model_name=report.get('mode', 'oracle'))

def _record_event(events: list[dict[str, Any]], *, node_id: str, stage_id: str, app: str, function: str, args: dict[str, Any], response: dict[str, Any]) -> None:
    step = len(events) + 1
    events.append({'step': step, 'node_id': node_id, 'stage_id': stage_id, 'app': app, 'function': function, 'agent_action': f'{app}.{function}', 'args': args, 'response': response})

def _write_jsonl(path: Path, rows: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text('\n'.join((json.dumps(row, ensure_ascii=False) for row in rows)) + '\n', encoding='utf-8')

def _safe_task_dir_name(task_id: str) -> str:
    return ''.join((ch if ch.isalnum() or ch in {'_', '-'} else '_' for ch in task_id))

def _avg(values: list[float]) -> float:
    return round(sum(values) / len(values), 4) if values else 0.0
